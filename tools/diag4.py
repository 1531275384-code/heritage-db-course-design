# -*- coding: utf-8 -*-
import pymysql
c = pymysql.connect(host='127.0.0.1', port=3399, user='root', password='', charset='utf8mb4', autocommit=True)
cur = c.cursor()
cur.execute("DROP DATABASE IF EXISTS t4")
cur.execute("CREATE DATABASE t4 DEFAULT CHARACTER SET utf8mb4")
cur.execute("USE t4")
T = [
 ("S1 selfFK(plain) + compound CHECK",
  "CREATE TABLE s1 (id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, lv TINYINT NOT NULL, pid INT UNSIGNED NULL, CONSTRAINT fk1 FOREIGN KEY (pid) REFERENCES s1(id), CONSTRAINT ck1 CHECK ((lv=1 AND pid IS NULL) OR (lv=2 AND pid IS NOT NULL))) ENGINE=InnoDB"),
 ("S2 selfFK(plain) + 拆成两条单列CHECK",
  "CREATE TABLE s2 (id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, lv TINYINT NOT NULL, pid INT UNSIGNED NULL, CONSTRAINT fk2 FOREIGN KEY (pid) REFERENCES s2(id), CONSTRAINT ck2a CHECK (NOT (lv=1 AND pid IS NOT NULL)), CONSTRAINT ck2b CHECK (NOT (lv=2 AND pid IS NULL))) ENGINE=InnoDB"),
 ("S3 selfFK(cascade) + only lv CHECK",
  "CREATE TABLE s3 (id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, lv TINYINT NOT NULL, pid INT UNSIGNED NULL, CONSTRAINT fk3 FOREIGN KEY (pid) REFERENCES s3(id) ON DELETE RESTRICT ON UPDATE CASCADE, CONSTRAINT ck3 CHECK (lv IN (1,2))) ENGINE=InnoDB"),
 ("S4 selfFK(cascade) + only pid CHECK",
  "CREATE TABLE s4 (id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, lv TINYINT NOT NULL, pid INT UNSIGNED NULL, CONSTRAINT fk4 FOREIGN KEY (pid) REFERENCES s4(id) ON DELETE RESTRICT ON UPDATE CASCADE, CONSTRAINT ck4 CHECK (pid IS NULL OR pid > 0)) ENGINE=InnoDB"),
 ("S5 selfFK(cascade) + compound CHECK",
  "CREATE TABLE s5 (id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, lv TINYINT NOT NULL, pid INT UNSIGNED NULL, CONSTRAINT fk5 FOREIGN KEY (pid) REFERENCES s5(id) ON DELETE RESTRICT ON UPDATE CASCADE, CONSTRAINT ck5 CHECK ((lv=1 AND pid IS NULL) OR (lv=2 AND pid IS NOT NULL))) ENGINE=InnoDB"),
 ("S6 普通FK + compound CHECK",
  "CREATE TABLE s6 (id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, lv TINYINT NOT NULL, pid INT UNSIGNED NULL, CONSTRAINT fk6 FOREIGN KEY (pid) REFERENCES s2(id), CONSTRAINT ck6 CHECK ((lv=1 AND pid IS NULL) OR (lv=2 AND pid IS NOT NULL))) ENGINE=InnoDB"),
]
for n, s in T:
    try:
        cur.execute(s); print("OK   ", n)
    except Exception as e:
        print("FAIL ", n, "=>", e)
c.close()
